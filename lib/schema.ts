export const boosterStatusEnum = pgEnum('booster_status', ['active', 'inactive']);

// Manually-managed roster of boosters (качеры). No login/registration — admins
// add and edit these rows directly from /admin/boosters. Payout fields exist
// because each finished order splits revenue (booster commission vs. house);
// `balance` accumulates the booster's unpaid earnings, paid out off-platform.
export const boosters = pgTable('boosters', {
  id: uuid('id').defaultRandom().primaryKey(),
  // Portal access: links the roster row to a site account (users.role is set
  // to 'booster' on link). NULL = no portal access. The FK is the identity
  // that scopes portal queries; the role only gates the routes.
  userId: uuid('user_id').unique().references(() => users.id, { onDelete: 'set null' }),
  firstName: varchar('first_name', { length: 100 }).notNull(),
  lastName: varchar('last_name', { length: 100 }).notNull(),
  birthDate: timestamp('birth_date', { withTimezone: true }),
  telegramUsername: varchar('telegram_username', { length: 255 }),
  // Самозанятый: ИНН нужен для легального чека/выплаты через «Мой налог».
  inn: varchar('inn', { length: 12 }),
  // Куда платить: номер карты или телефон для СБП (свободная строка).
  payoutDetails: varchar('payout_details', { length: 255 }),
  // Доля качера от заказа в процентах (остальное — проекту). По умолчанию 40%.
  commissionPercent: integer('commission_percent').notNull().default(40),
  // Накопленный, ещё не выплаченный заработок. Decimal хранится как строка.
  balance: decimal('balance', { precision: 10, scale: 2 }).notNull().default('0'),
  status: boosterStatusEnum('status').notNull().default('active'),
  note: text('note'),
  startDate: timestamp('start_date', { withTimezone: true }).defaultNow(),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
});

export const boosterDocTypeEnum = pgEnum('booster_doc_type', ['agreement', 'passport']);

// Personal documents (договор + скан паспорта) for each booster. The files
// themselves live in the PRIVATE bucket (`whaleabyss-private`) — never in the
// public one — and are only reachable by streaming through the admin-guarded
// API route. One document of each type per booster; re-upload replaces.
export const boosterDocuments = pgTable('booster_documents', {
  id: uuid('id').defaultRandom().primaryKey(),
  boosterId: uuid('booster_id').notNull().references(() => boosters.id, { onDelete: 'cascade' }),
  docType: boosterDocTypeEnum('doc_type').notNull(),
  // Key inside the private bucket — random suffix, no PII in the key itself.
  s3Key: varchar('s3_key', { length: 512 }).notNull(),
  // Original filename, kept only for the download dialog.
  fileName: varchar('file_name', { length: 255 }).notNull(),
  mimeType: varchar('mime_type', { length: 100 }).notNull(),
  sizeBytes: integer('size_bytes').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
}, (t) => [
  unique('booster_documents_booster_doc_type_unique').on(t.boosterId, t.docType),
]);